/* eslint-disable @typescript-eslint/no-explicit-any */
"use client";

import { memo, useMemo, useRef } from "react";
import { useFrame } from "@react-three/fiber";
import { useGLTF } from "@react-three/drei";
import * as THREE from "three";
import { clone as cloneSkeleton } from "three/examples/jsm/utils/SkeletonUtils.js";
import { WORLD, getSoftTexture } from "./environment";

export type RhinoVariant = "player" | "enemy";

const MODEL_URL = "/models/rhino.glb";

// Cartoon palette — light-gray hero vs charcoal rival. Applied at load by
// MATERIAL NAME (Body/Fold/Horn/Hoof/Eye/InnerEar — authored in
// scripts/build-rhino-model.mjs).
const PALETTE = {
    player: { body: "#aeb8c2", fold: "#96a1ac", horn: "#f2e8cf", hoof: "#5d6670", eye: "#1f2937", innerEar: "#7d8791" },
    enemy: { body: "#5d646c", fold: "#4a5057", horn: "#e0d0ab", hoof: "#31363c", eye: "#dc2626", innerEar: "#3a3f45" },
} as const;

const clamp = (v: number, a: number, b: number) => Math.max(a, Math.min(b, v));
const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const easeOutCubic = (t: number) => 1 - Math.pow(1 - t, 3);

// =========================================================================
// 🦏 RHINO — loads the authored GLB (public/models/rhino.glb, generated by
// scripts/build-rhino-model.mjs). The GLB's named node hierarchy IS the
// animation rig: Body (bob/lean/lunge), Head (butt tilts), Tail (swish),
// LegFR/FL/BR/BL (hip-pivot gait). No baked clips — the game drives the
// pivots every frame from stateRef so gait speed tracks live typing force:
//   - countdown: walks in (player from state.entryFrom, rival from the right)
//   - battle: strain cycle, lean from pushVel, lunge/flinch/recoil overlays,
//     enemy rage rear-up
//   - fall: pose comes straight from state.falling
//   - idle (menu): breathing bob + tail swish
// One GLB serves both sides — materials are cloned & tinted per variant.
// =========================================================================
export const Rhino = memo(({ variant, stateRef }: { variant: RhinoVariant; stateRef: any }) => {
    const { scene } = useGLTF(MODEL_URL);
    const isPlayer = variant === "player";
    const dir = isPlayer ? 1 : -1;

    // Per-instance clone with tinted materials + pivot lookup
    const rig = useMemo(() => {
        const p = PALETTE[variant];
        const obj = cloneSkeleton(scene);
        const tint: Record<string, string> = {
            Body: p.body, Fold: p.fold, Horn: p.horn, Hoof: p.hoof, Eye: p.eye, InnerEar: p.innerEar,
        };
        const matCache = new Map<string, THREE.Material>();
        obj.traverse((o: any) => {
            if (!o.isMesh) return;
            const name = o.material?.name as string;
            if (!matCache.has(name)) {
                const m = o.material.clone() as THREE.MeshStandardMaterial;
                if (tint[name]) m.color.set(tint[name]);
                if (name === "Eye" && !isPlayer) {
                    m.emissive.set("#7f1d1d");
                    m.emissiveIntensity = 0.9;
                }
                matCache.set(name, m);
            }
            o.material = matCache.get(name);
            // the angry brow ridges belong to the rival only
            if (isPlayer && (o.name === "BrowR" || o.name === "BrowL")) o.visible = false;
        });
        const get = (n: string) => obj.getObjectByName(n) as THREE.Object3D;
        return {
            obj,
            body: get("Body"),
            head: get("Head"),
            tail: get("Tail"),
            legs: [get("LegFR"), get("LegFL"), get("LegBR"), get("LegBL")],
        };
    }, [scene, variant, isPlayer]);

    const rootRef = useRef<THREE.Group>(null!);
    const shadowMatRef = useRef<THREE.MeshBasicMaterial>(null!);

    // Overlay animation timers (local to this instance)
    const anim = useRef({ lastLunge: 0, lungeT: 0, lastFlinch: 0, flinchT: 0, lastHit: 0, hitT: 0 });

    useFrame((rootState, delta) => {
        const dt = Math.min(delta, 0.1);
        const s = stateRef.current;
        const t = rootState.clock.elapsedTime;
        const root = rootRef.current;
        const { body, head, tail, legs } = rig;
        if (!root || !body || !head || !tail) return;
        const a = anim.current;
        const gap = WORLD.RHINO_GAP;

        // --- overlay triggers ---
        if (isPlayer) {
            if (s.lungeCount !== a.lastLunge) { a.lastLunge = s.lungeCount; a.lungeT = 0.3; }
            if (s.flinchCount !== a.lastFlinch) { a.lastFlinch = s.flinchCount; a.flinchT = 0.4; }
        } else {
            // the player's word-complete lunge is what knocks the enemy back
            if (s.lungeCount !== a.lastHit) { a.lastHit = s.lungeCount; a.hitT = 0.35; }
        }
        a.lungeT = Math.max(0, a.lungeT - dt);
        a.flinchT = Math.max(0, a.flinchT - dt);
        a.hitT = Math.max(0, a.hitT - dt);

        // --- root placement ---
        let x: number, y = 0, rot = 0;
        const fallingMe = s.falling && s.falling.who === variant;
        if (fallingMe) {
            x = s.falling.x; y = s.falling.y; rot = s.falling.rot;
        } else if (s.phase === "idle") {
            x = -dir * (gap + 0.7);
        } else if (s.phase === "countdown") {
            // player returns from wherever it won the last shove; each new
            // rival always charges in from the right edge
            const e = easeOutCubic(clamp(s.entry, 0, 1));
            const from = isPlayer ? (s.entryFrom ?? -9.5) : 9.5;
            x = lerp(from, -dir * gap, e);
        } else {
            x = s.pushX - dir * gap;
        }

        // winner celebration hops while the loser tumbles
        const celebrating = s.victor === variant && (s.phase === "fall" || s.phase === "roundover");
        if (celebrating) y += Math.abs(Math.sin(t * 5.2)) * 0.3;

        root.position.set(x, y, 0);
        root.rotation.set(0, isPlayer ? 0 : Math.PI, rot);
        if (shadowMatRef.current) shadowMatRef.current.opacity = clamp(0.26 * (1 + y * 1.5), 0, 0.26);

        // --- body / head / legs animation (all in local space, +x = forward) ---
        let bodyBob = 0, tilt = 0, thrust = 0, headTilt = 0, legAmp = 0, freq = 5;

        if (fallingMe) {
            // flail
            legAmp = 0.9; freq = 11;
            headTilt = Math.sin(t * 9) * 0.3;
        } else if (s.phase === "idle" || s.phase === "roundover") {
            bodyBob = Math.sin(t * 1.7 + dir) * 0.03;
            headTilt = Math.sin(t * 0.9 + dir * 2) * 0.05;
            legAmp = 0; freq = 0;
            if (celebrating) { headTilt = Math.sin(t * 6) * 0.35; }
        } else {
            const walking = s.phase === "countdown";
            const striving = s.phase === "battle";
            const myAdvance = striving ? (s.pushVel || 0) * dir : 0; // + = I'm winning ground
            freq = walking
                ? 8
                : isPlayer
                    ? 5 + Math.min(6, (s.playerForce || 0) * 4)
                    : 5.5 + ((s.enemyPushMul || 1) - 1) * 2.5;
            legAmp = walking ? 0.5 : 0.42;
            bodyBob = Math.abs(Math.sin(t * freq)) * (walking ? 0.07 : 0.05);
            tilt = striving ? -0.1 - clamp(myAdvance, -1, 1) * 0.06 : 0;
            headTilt = striving ? -0.26 : -0.05; // head-down shoving posture

            if (isPlayer) {
                if (a.lungeT > 0) { const q = Math.sin((a.lungeT / 0.3) * Math.PI); thrust += q * 0.32; headTilt -= q * 0.3; }
                if (a.flinchT > 0) { const q = Math.sin((a.flinchT / 0.4) * Math.PI); tilt += q * 0.28; thrust -= q * 0.3; headTilt += q * 0.35; }
            } else {
                if (a.hitT > 0) { const q = Math.sin((a.hitT / 0.35) * Math.PI); tilt += q * 0.22; thrust -= q * 0.35; headTilt += q * 0.4; }
                if (s.ragePhase === "tele") { const q = clamp(1 - s.rageT / 0.8, 0, 1); tilt += q * 0.5; headTilt += q * 0.55; thrust -= q * 0.2; }
                else if (s.ragePhase === "shove") { const q = clamp(s.rageT / 0.7, 0, 1); tilt -= q * 0.16; thrust += q * 0.3; headTilt -= q * 0.25; }
            }
        }

        body.position.set(thrust, 1.12 + bodyBob, 0);
        body.rotation.z = tilt;
        head.rotation.z = headTilt;
        tail.rotation.x = Math.sin(t * 3.1 + dir * 1.7) * 0.35;

        for (let i = 0; i < legs.length; i++) {
            if (!legs[i]) continue;
            // diagonal gait pairs
            const ph = (i === 0 || i === 3) ? 0 : Math.PI;
            const raged = !isPlayer && s.ragePhase === "tele" && i < 2 ? 0.85 : 0; // front legs paw the air
            legs[i].rotation.z = (freq > 0 ? Math.sin(t * freq + ph) * legAmp : 0) + raged;
        }
    });

    return (
        <group ref={rootRef} scale={0.85}>
            {/* blob shadow */}
            <mesh rotation={[-Math.PI / 2, 0, 0]} position={[0, 0.02, 0]}>
                <circleGeometry args={[1.5, 24]} />
                <meshBasicMaterial ref={shadowMatRef} map={getSoftTexture()} transparent opacity={0.26} color="#173a1c" depthWrite={false} />
            </mesh>
            <primitive object={rig.obj} />
        </group>
    );
});
Rhino.displayName = "Rhino";

useGLTF.preload(MODEL_URL);
